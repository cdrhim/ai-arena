import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { loadPartnerDirectory } from "../netlify/lib/program-hub.mjs";

const ROOT = process.cwd();
const ASSET_DIRECTORY = path.join(ROOT, "public", "arena", "assets", "company-logos");
const CLIENT_DATA_PATH = path.join(ROOT, "public", "arena", "company-logo-data.js");
const SOURCE_MANIFEST_PATH = path.join(ROOT, "outputs", "company-logo-sources.json");
const OVERRIDES_PATH = path.join(ROOT, "scripts", "company-logo-overrides.json");
const USER_AGENT = "SparkClaw-Arena-Logo-Collector/1.0 (+https://sparkclaw-arena.netlify.app/)";
const REQUEST_TIMEOUT_MS = 12_000;
const MAX_HTML_BYTES = 1_500_000;
const MAX_IMAGE_BYTES = 2_500_000;

const directory = (await loadPartnerDirectory()).filter((team) => !isTestTeam(team));
const overrides = JSON.parse(await readFile(OVERRIDES_PATH, "utf8"));
await mkdir(ASSET_DIRECTORY, { recursive: true });
await mkdir(path.dirname(SOURCE_MANIFEST_PATH), { recursive: true });

const previous = await readPreviousManifest();
const previousById = new Map((previous.teams || []).map((item) => [String(item.teamId), item]));
const results = await mapWithConcurrency(directory, 6, async (team, index) => {
  const override = overrides[String(team.id)] || {};
  const websiteUrl = primaryWebsiteUrl(override.websiteUrl || team.websiteUrl);
  const prior = previousById.get(String(team.id));
  process.stderr.write(`[${index + 1}/${directory.length}] ${team.name}\n`);

  if (override.assetPath) {
    return sourceRecord(team, {
      websiteUrl,
      sourceUrl: override.sourceUrl || "curated local asset",
      assetPath: override.assetPath,
      status: "curated_local",
      tone: override.tone || "light"
    });
  }

  if (!websiteUrl) {
    return sourceRecord(team, { status: "missing_website" });
  }

  try {
    if (override.logoUrl) {
      const image = await fetchImage(override.logoUrl);
      const extension = extensionForImage(image.contentType, override.logoUrl, image.bytes);
      if (!extension) throw new Error("Unsupported logo format");
      const assetName = `${team.id}.${extension}`;
      const bytes = extension === "svg" ? sanitizeSvg(image.bytes) : image.bytes;
      await writeFile(path.join(ASSET_DIRECTORY, assetName), bytes);
      return sourceRecord(team, {
        websiteUrl,
        resolvedWebsiteUrl: websiteUrl,
        sourceUrl: override.logoUrl,
        assetPath: `/arena/assets/company-logos/${assetName}`,
        status: "curated_download",
        tone: override.tone || "light"
      });
    }

    const page = await fetchLimited(websiteUrl, MAX_HTML_BYTES, "text/html");
    const selected = selectHeaderLogo(page.text, page.url, team);
    if (!selected) {
      return sourceRecord(team, { websiteUrl, status: "logo_not_found" });
    }

    const image = await fetchImage(selected.url);
    const extension = extensionForImage(image.contentType, selected.url, image.bytes);
    if (!extension) throw new Error("Unsupported logo format");

    const assetName = `${team.id}.${extension}`;
    const assetPath = path.join(ASSET_DIRECTORY, assetName);
    const bytes = extension === "svg" ? sanitizeSvg(image.bytes) : image.bytes;
    await writeFile(assetPath, bytes);

    return sourceRecord(team, {
      websiteUrl,
      resolvedWebsiteUrl: page.url,
      sourceUrl: selected.url,
      assetPath: `/arena/assets/company-logos/${assetName}`,
        status: "collected",
        tone: override.tone || "light"
    });
  } catch (error) {
    if (prior?.status === "collected" && prior?.assetPath) {
      return { ...prior, status: "retained_previous", checkedAt: new Date().toISOString() };
    }
    return sourceRecord(team, { websiteUrl, status: "fetch_failed", error: safeError(error) });
  }
});

const generatedAt = new Date().toISOString();
const collected = results.filter((item) => item.assetPath);
const clientRows = Object.fromEntries(
  collected.map((item) => [
    item.teamId,
    {
      src: item.assetPath,
      websiteHost: hostname(item.resolvedWebsiteUrl || item.websiteUrl),
      tone: item.tone || "light"
    }
  ])
);

await writeFile(
  CLIENT_DATA_PATH,
  `// Generated by scripts/collect-company-logos.mjs.\nexport const COMPANY_LOGOS = Object.freeze(${JSON.stringify(
    clientRows,
    null,
    2
  )});\n`,
  "utf8"
);
await writeFile(
  SOURCE_MANIFEST_PATH,
  `${JSON.stringify({ generatedAt, teamCount: directory.length, collectedCount: collected.length, teams: results }, null, 2)}\n`,
  "utf8"
);

process.stdout.write(
  `${JSON.stringify({ teamCount: directory.length, collectedCount: collected.length, missingWebsiteCount: results.filter((item) => item.status === "missing_website").length, failedCount: results.filter((item) => item.status === "fetch_failed").length })}\n`
);

function isTestTeam(team) {
  const value = `${team.name || ""} ${team.companyName || ""}`.trim().toLowerCase();
  return value === "test test" || value === "test" || value.includes("test1@gmail.com");
}

function primaryWebsiteUrl(value) {
  const input = String(value || "").trim();
  if (!input) return "";
  const starts = [...input.matchAll(/https?:\/\//gi)].map((match) => match.index);
  const first = starts[0];
  if (!Number.isInteger(first)) return "";
  const second = starts.find((position) => position > first);
  let candidate = input.slice(first, second ?? input.length);
  candidate = candidate.split(/%20-%20|\s|[<>{}\[\]"']/)[0];
  try {
    const url = new URL(candidate);
    if (!/^https?:$/.test(url.protocol)) return "";
    return url.href;
  } catch {
    return "";
  }
}

async function fetchLimited(url, maxBytes, expectedType) {
  const response = await fetchWithTimeout(url, {
    headers: {
      accept: expectedType === "text/html" ? "text/html,application/xhtml+xml" : "image/avif,image/webp,image/svg+xml,image/*,*/*;q=0.5",
      "user-agent": USER_AGENT
    },
    redirect: "follow"
  });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const contentLength = Number(response.headers.get("content-length") || 0);
  if (contentLength > maxBytes) throw new Error("Response too large");
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length > maxBytes) throw new Error("Response too large");
  return {
    bytes,
    text: bytes.toString("utf8"),
    contentType: String(response.headers.get("content-type") || "").toLowerCase(),
    url: response.url || url
  };
}

async function fetchImage(url) {
  const response = await fetchLimited(url, MAX_IMAGE_BYTES, "image");
  const type = response.contentType;
  const looksLikeSvg = response.bytes.toString("utf8", 0, Math.min(500, response.bytes.length)).includes("<svg");
  if (!type.startsWith("image/") && !looksLikeSvg) throw new Error("Logo URL did not return an image");
  return response;
}

async function fetchWithTimeout(url, options) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
}

function selectHeaderLogo(html, pageUrl, team) {
  const source = String(html || "").slice(0, MAX_HTML_BYTES);
  const headerRanges = elementRanges(source, ["header", "nav"]);
  const nameTokens = brandTokens(team);
  const candidates = [];
  const imagePattern = /<img\b[^>]*>/gi;
  let match;
  while ((match = imagePattern.exec(source))) {
    const attributes = parseAttributes(match[0]);
    const rawSource = firstImageSource(attributes);
    if (!rawSource) continue;
    let url;
    try {
      url = new URL(rawSource, pageUrl).href;
    } catch {
      continue;
    }
    if (!/^https?:\/\//i.test(url)) continue;
    const descriptor = `${attributes.alt || ""} ${attributes.class || ""} ${attributes.id || ""} ${attributes.title || ""} ${rawSource}`.toLowerCase();
    const insideHeader = headerRanges.some(([start, end]) => match.index >= start && match.index <= end);
    const score = logoCandidateScore({ descriptor, index: match.index, insideHeader, url, nameTokens, attributes });
    candidates.push({ url, score, index: match.index });
  }
  candidates.sort((left, right) => right.score - left.score || left.index - right.index);
  return candidates[0]?.score >= 40 ? candidates[0] : null;
}

function logoCandidateScore({ descriptor, index, insideHeader, url, nameTokens, attributes }) {
  let score = 0;
  if (insideHeader) score += 55;
  if (/\blogo\b|logo[-_]/i.test(descriptor)) score += 95;
  if (/\bbrand\b|wordmark|logotype/i.test(descriptor)) score += 50;
  if (nameTokens.some((token) => token.length >= 3 && descriptor.includes(token))) score += 34;
  if (index < 25_000) score += 24;
  else if (index < 80_000) score += 12;
  if (/\.(svg|png|webp)(?:[?#]|$)/i.test(url)) score += 14;
  if (/header|navbar|gnb|navigation/i.test(descriptor)) score += 18;
  if (/favicon|avatar|profile|social|instagram|facebook|youtube|flag|language|search|menu|banner|hero|qr|app[-_]?store|play[-_]?store/i.test(descriptor)) score -= 120;
  const width = Number.parseInt(attributes.width || "", 10);
  const height = Number.parseInt(attributes.height || "", 10);
  if (Number.isFinite(width) && Number.isFinite(height)) {
    if (width >= height * 1.4) score += 12;
    if (width <= 24 && height <= 24) score -= 45;
  }
  return score;
}

function elementRanges(html, tags) {
  const ranges = [];
  for (const tag of tags) {
    const pattern = new RegExp(`<${tag}\\b[^>]*>[\\s\\S]*?<\\/${tag}>`, "gi");
    let match;
    while ((match = pattern.exec(html))) ranges.push([match.index, match.index + match[0].length]);
  }
  return ranges;
}

function parseAttributes(tag) {
  const attributes = {};
  const pattern = /([:\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/g;
  let match;
  while ((match = pattern.exec(tag))) attributes[match[1].toLowerCase()] = match[2] ?? match[3] ?? match[4] ?? "";
  return attributes;
}

function firstImageSource(attributes) {
  const direct = attributes.src || attributes["data-src"] || attributes["data-lazy-src"] || "";
  if (direct && !direct.startsWith("data:")) return direct;
  const srcset = attributes.srcset || attributes["data-srcset"] || "";
  return srcset.split(",")[0]?.trim().split(/\s+/)[0] || "";
}

function brandTokens(team) {
  return `${team.name || ""} ${team.companyName || ""}`
    .toLowerCase()
    .replace(/주식회사|\(주\)|inc\.?|co\.?|ltd\.?/g, " ")
    .split(/[^a-z0-9가-힣]+/)
    .filter((token) => token.length >= 2);
}

function extensionForImage(contentType, url, bytes) {
  if (contentType.includes("svg") || bytes.toString("utf8", 0, Math.min(500, bytes.length)).includes("<svg")) return "svg";
  if (contentType.includes("png") || bytes.subarray(1, 4).toString("ascii") === "PNG") return "png";
  if (contentType.includes("webp") || bytes.subarray(8, 12).toString("ascii") === "WEBP") return "webp";
  if (contentType.includes("jpeg") || contentType.includes("jpg") || (bytes[0] === 0xff && bytes[1] === 0xd8)) return "jpg";
  if (contentType.includes("gif") || bytes.subarray(0, 3).toString("ascii") === "GIF") return "gif";
  const match = String(url).match(/\.(svg|png|webp|jpe?g|gif)(?:[?#]|$)/i);
  return match ? match[1].toLowerCase().replace("jpeg", "jpg") : "";
}

function sanitizeSvg(bytes) {
  let svg = bytes.toString("utf8");
  svg = svg.replace(/<script\b[\s\S]*?<\/script>/gi, "");
  svg = svg.replace(/<foreignObject\b[\s\S]*?<\/foreignObject>/gi, "");
  svg = svg.replace(/\son[a-z]+\s*=\s*(?:"[^"]*"|'[^']*')/gi, "");
  svg = svg.replace(/\s(?:href|xlink:href)\s*=\s*(?:"https?:[^"]*"|'https?:[^']*')/gi, "");
  return Buffer.from(svg, "utf8");
}

function sourceRecord(team, values = {}) {
  return {
    teamId: String(team.id || ""),
    name: String(team.name || ""),
    websiteUrl: values.websiteUrl || primaryWebsiteUrl(team.websiteUrl),
    resolvedWebsiteUrl: values.resolvedWebsiteUrl || "",
    sourceUrl: values.sourceUrl || "",
    assetPath: values.assetPath || "",
    status: values.status || "unknown",
    error: values.error || "",
    tone: values.tone || "light",
    checkedAt: new Date().toISOString()
  };
}

function hostname(value) {
  try {
    return new URL(value).hostname.replace(/^www\./i, "");
  } catch {
    return "";
  }
}

function safeError(error) {
  const message = error instanceof Error ? error.message : String(error || "Unknown error");
  return message.replace(/[\r\n]+/g, " ").slice(0, 180);
}

async function readPreviousManifest() {
  try {
    return JSON.parse(await readFile(SOURCE_MANIFEST_PATH, "utf8"));
  } catch {
    return { teams: [] };
  }
}

async function mapWithConcurrency(items, limit, worker) {
  const results = new Array(items.length);
  let nextIndex = 0;
  async function run() {
    while (nextIndex < items.length) {
      const index = nextIndex++;
      results[index] = await worker(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, run));
  return results;
}
