import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(ROOT, "outputs", "company-external-link-sources.json");
const outputPath = path.join(ROOT, "public", "arena", "company-external-link-data.js");
const manifest = JSON.parse(await readFile(inputPath, "utf8"));
const data = Object.fromEntries(
  manifest.teams
    .filter((team) => team.links?.length)
    .map((team) => [
      String(team.teamId),
      team.links.map((link) => ({
        kind: String(link.kind),
        label: String(link.label),
        url: String(link.url),
        verificationStatus: String(link.verificationStatus || "verified"),
        verifiedAt: String(link.verifiedAt || team.checkedAt || manifest.generatedAt || "")
      }))
    ])
);

const source = `// Generated by scripts/generate-company-external-link-data.mjs.\nexport const COMPANY_EXTERNAL_LINKS = Object.freeze(${JSON.stringify(data, null, 2)});\n`;
await writeFile(outputPath, source, "utf8");
console.log(JSON.stringify({ teams: Object.keys(data).length, output: outputPath }));
